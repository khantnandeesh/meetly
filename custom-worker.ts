/**
 * The Worker Cloudflare runs: OpenNext's generated Worker for every request, plus the webinar
 * cost watchdog once a minute (`triggers.crons` in wrangler.jsonc), plus Live (beta)'s
 * coordinator: the overlay's Durable Object, and the WebSocket upgrades that reach it.
 *
 * OpenNext's own Worker (.open-next/worker.js, made by `opennextjs-cloudflare build`) only has a
 * fetch handler. This is the adapter's documented way to add another: a custom Worker that
 * re-uses that fetch handler and is named as `main` in wrangler.jsonc
 * (https://opennext.js.org/cloudflare/howtos/custom-worker). Nothing here uses the Durable Object
 * queue or tag cache (open-next.config.ts serves prerendered pages from static assets); the one
 * Durable Object exported is Live's coordinator, `OverlayRoom`.
 */

// eslint-disable-next-line @typescript-eslint/ban-ts-comment -- the file exists only after a build; @ts-expect-error would fail once it does.
// @ts-ignore `.open-next/worker.js` is generated by `opennextjs-cloudflare build`.
import { default as handler } from "./.open-next/worker.js";
import { OverlayRoom as CoordinatorRoom, type CoordinatorEnv, type DurableObjectStateLike } from "./packages/overlay/coordinator/durableObject";
import type { IceServer } from "./packages/overlay/protocol";
import { runScheduledCostGuard, type CostGuardEnv } from "./src/lib/costGuard.server";
import { environmentLabel, labelResponse, robotsResponse, type HtmlRewriter } from "./src/lib/environmentLabel";
import { LIVE_VIEWER_CAP } from "./src/lib/live/tree";

type Env = Record<string, unknown>;
type Context = { waitUntil(promise: Promise<unknown>): void };

/** The Worker's variables and secrets that are text: its bindings (ASSETS, …) are not settings. */
const settings = (env: Env): CostGuardEnv =>
  Object.fromEntries(Object.entries(env).filter((entry): entry is [string, string] => typeof entry[1] === "string"));

/**
 * Live (beta)'s STUN servers. With a Cloudflare TURN key (the secrets TURN_KEY_ID and
 * TURN_KEY_API_TOKEN, SPEC §6.7) each peer is also given TURN credentials of its own, so a viewer
 * behind a strict NAT (symmetric NAT, a strict firewall, some mobile carriers) can watch; such a
 * viewer only watches and never relays ([D80]). Without the key, it can't connect to anyone.
 */
const LIVE_STUN: IceServer[] = [{ urls: ["stun:stun.cloudflare.com:3478"] }, { urls: ["stun:stun.l.google.com:19302"] }];

/** A local run's own settings: in a local .dev.vars only, never deployed. */
type LocalEnv = { OVERLAY_LOCAL_ONE_NETWORK?: string; OVERLAY_TEST_TURN_URL?: string; OVERLAY_TEST_TURN_SECRET?: string; OVERLAY_TEST_TURN_TTL_S?: string };

/**
 * Live (beta)'s coordinator: one Durable Object per stream (bound as OVERLAY_ROOM in
 * wrangler.jsonc), with Live's STUN servers and its audience of 50. `OVERLAY_LOCAL_ONE_NETWORK`
 * ("1", in a local .dev.vars only, never deployed) offers no STUN, for a local run on a machine
 * with no route out: every browser on it reaches the others by its host candidates. With it, the
 * `OVERLAY_TEST_TURN_*` variables point the coordinator at a local TURN server (coturn with
 * `use-auth-secret`) for the strict-NAT browser test (test/e2e/serverless.cjs `strict-nat`).
 */
export class OverlayRoom extends CoordinatorRoom {
  constructor(state: DurableObjectStateLike, env: CoordinatorEnv & LocalEnv) {
    const local = env.OVERLAY_LOCAL_ONE_NETWORK === "1";
    const testTurn =
      local && env.OVERLAY_TEST_TURN_URL && env.OVERLAY_TEST_TURN_SECRET
        ? { urls: env.OVERLAY_TEST_TURN_URL.split(","), secret: env.OVERLAY_TEST_TURN_SECRET, ttlS: Number(env.OVERLAY_TEST_TURN_TTL_S) > 0 ? Number(env.OVERLAY_TEST_TURN_TTL_S) : 3600 }
        : undefined;
    super(state, env, { stun: local ? [] : LIVE_STUN, viewerCap: LIVE_VIEWER_CAP, testTurn });
  }
}

/** `/api/live/<id>`, the share id shaped like a meeting code: its WebSocket goes to the stream's coordinator. */
const LIVE_SOCKET = /^\/api\/live\/([a-z]{3}-[a-z]{4}-[a-z]{3})$/;

function liveSocket(request: Request, rooms: CoordinatorEnv["OVERLAY_ROOM"], id: string): Promise<Response> {
  const url = new URL(request.url);
  // The coordinator's own path for a session's socket, with the ticket (`?ticket=`) as it came.
  const target = new URL(`/overlay/v1/rooms/${id}/ws${url.search}`, url.origin);
  const headers = new Headers(request.headers);
  headers.set("x-overlay-room", id);
  return rooms.get(rooms.idFromName(id)).fetch(new Request(target, { method: "GET", headers }));
}

const next = handler as { fetch: (request: Request, env: Env, ctx: Context) => Promise<Response> };

/** The Workers runtime's HTMLRewriter (a global there; absent anywhere else). */
const htmlRewriter = (): HtmlRewriter => new (globalThis as unknown as { HTMLRewriter: new () => HtmlRewriter }).HTMLRewriter();

function respond(request: Request, env: Env, ctx: Context): Promise<Response> {
  const live = LIVE_SOCKET.exec(new URL(request.url).pathname);
  const rooms = env.OVERLAY_ROOM as CoordinatorEnv["OVERLAY_ROOM"] | undefined;
  if (live && rooms && request.headers.get("upgrade")?.toLowerCase() === "websocket") return liveSocket(request, rooms, live[1]);
  return next.fetch(request, env, ctx);
}

const worker = {
  async fetch(request: Request, env: Env, ctx: Context): Promise<Response> {
    // Production has no label, and answers exactly as before.
    const label = environmentLabel(env.MEETLY_ENVIRONMENT_LABEL);
    if (!label) return respond(request, env, ctx);
    // Staging (src/lib/environmentLabel.ts): kept out of search engines, and marked on every page.
    if (new URL(request.url).pathname === "/robots.txt") return robotsResponse();
    return labelResponse(await respond(request, env, ctx), label, htmlRewriter);
  },

  /**
   * Every minute: end webinars past their free participant-minutes, warn the ones near it, and
   * end every webinar while they are switched off (src/lib/costGuard.server.ts). It never
   * throws; whatever fails is tried again the next minute.
   */
  async scheduled(_controller: unknown, env: Env, ctx: Context): Promise<void> {
    ctx.waitUntil(runScheduledCostGuard(settings(env)));
  },
};

export default worker;
